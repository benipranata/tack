package generate

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/benipranata/tack/internal/render"
)

// action is a change to make on disk.
type action struct {
	path    string
	content []byte
	remove  bool
}

func (a action) apply() error {
	if a.remove {
		return os.Remove(a.path)
	}
	if err := os.MkdirAll(filepath.Dir(a.path), 0o755); err != nil {
		return err
	}
	return writeAtomic(a.path, a.content)
}

// Write applies files under root. It writes nothing unless every file is safe to touch:
// a file tack did not generate is never overwritten or removed.
func Write(root string, files []render.File) error {
	actions, err := plan(root, files)
	if err != nil {
		return err
	}
	for _, a := range actions {
		if err := a.apply(); err != nil {
			return err
		}
	}
	return nil
}

// plan lists the changes needed, leaving out files that are already up to date or already gone.
func plan(root string, files []render.File) ([]action, error) {
	var actions []action
	var errs []error
	for _, f := range files {
		name := filepath.Join(root, filepath.FromSlash(f.Path))
		existing, err := os.ReadFile(name)
		missing := errors.Is(err, fs.ErrNotExist)
		if err != nil && !missing {
			errs = append(errs, err)
			continue
		}
		if !missing && !render.IsGenerated(existing) {
			verb := "overwrite"
			if f.Remove {
				verb = "remove"
			}
			errs = append(errs, fmt.Errorf("%s: refusing to %s a file not generated by tack", f.Path, verb))
			continue
		}

		switch {
		case f.Remove && !missing:
			actions = append(actions, action{path: name, remove: true})
		case !f.Remove && !bytes.Equal(existing, f.Content):
			actions = append(actions, action{path: name, content: f.Content})
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	return actions, nil
}

// writeAtomic replaces name in one step, so a reader never sees a half-written file.
func writeAtomic(name string, content []byte) error {
	tmp := name + ".tmp"
	if err := os.WriteFile(tmp, content, 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, name); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}
