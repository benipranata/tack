package gen

import (
	"bytes"
	"fmt"
	"go/types"
	"path/filepath"
	"text/template"

	"github.com/benipranata/tack/internal/resolve"
	"golang.org/x/tools/imports"
)

type methodData struct {
	Name             string // e.g. MethodA
	LocalVar         string // e.g. methodA
	CleanupVar       string // e.g. methodACleanup
	FieldName        string // e.g. methodA
	TypeStr          string // e.g. a.IA, *c.C
	ProviderCall     string // e.g. provider01.ProvideA, or ProvideC (unqualified)
	ProviderFuncName string // e.g. ProvideA
}

type fileData struct {
	PackageName     string
	ConstructorName string
	IfaceRef        string // the interface's type reference as used in this file: bare (same package) or qualified (e.g. state.State, cross-package)
	StructName      string
	TestStructName  string
	TestCtorName    string
	GroupA          []importEntry
	GroupB          []importEntry
	Methods         []methodData
}

var fileTemplate = template.Must(template.New("wiring").Parse(`// Code generated by tack. DO NOT EDIT.

package {{.PackageName}}

import (
{{range .GroupA}}	{{if .Alias}}{{.Alias}} {{end}}{{printf "%q" .Path}}
{{end}}
{{range .GroupB}}	{{if .Alias}}{{.Alias}} {{end}}{{printf "%q" .Path}}
{{end}})

func {{.ConstructorName}}(ctx context.Context) ({{.IfaceRef}}, func(), error) {
	var cleanups []func()
	cleanup := func() {
		for i := len(cleanups) - 1; i >= 0; i-- {
			cleanups[i]()
		}
	}

{{range .Methods}}	// provide {{.Name}}() type of {{.TypeStr}}
	{{.LocalVar}}, {{.CleanupVar}}, err := {{.ProviderCall}}(ctx)
	if err != nil {
		cleanup()
		return nil, nil, fmt.Errorf({{printf "%q" (printf "%s: %%w" .ProviderFuncName)}}, err)
	}
	if {{.CleanupVar}} != nil {
		cleanups = append(cleanups, {{.CleanupVar}})
	}

{{end}}	return &{{.StructName}}{
{{range .Methods}}		{{.FieldName}}: {{.LocalVar}},
{{end}}	}, cleanup, nil
}

var _ {{.IfaceRef}} = (*{{.StructName}})(nil)

type {{.StructName}} struct {
{{range .Methods}}	{{.FieldName}} {{.TypeStr}}
{{end}}}
{{range .Methods}}
// {{.Name}} implements [{{$.IfaceRef}}].
func (i *{{$.StructName}}) {{.Name}}() {{.TypeStr}} {
	return i.{{.FieldName}}
}
{{end}}
type {{.TestStructName}} struct {
	_ struct{} // enforce keyed fields; see writeStructDecl
{{range .Methods}}	{{.Name}} {{.TypeStr}}
{{end}}}

func {{.TestCtorName}}(t testing.TB, s {{.TestStructName}}) {{.IfaceRef}} {
	t.Helper()
{{range .Methods}}	if s.{{.Name}} == nil {
		t.Fatalf("%s.%s not set", {{printf "%q" $.TestStructName}}, {{printf "%q" .Name}})
	}
{{end}}	return &{{.StructName}}{
{{range .Methods}}		{{.FieldName}}: s.{{.Name}},
{{end}}	}
}
`))

// Generate renders the gofmt-formatted generated wiring file source for a
// fully resolved output variant.
func Generate(iface *resolve.Interface) ([]byte, error) {
	// The generated file's own package is the output variant's effective
	// directory, not necessarily the interface's own declaring package.
	// When that directory has no .go files yet (a freshly scaffolded or
	// otherwise empty output package), there is no loaded package to read a
	// path/name from; targetPkgPath stays "" (never a real import path, so
	// it can never wrongly suppress an import) and the package clause is
	// derived from the directory's basename instead.
	targetPkgPath := ""
	packageName := filepath.Base(iface.EffectiveDir)
	if iface.OutputPkg != nil {
		targetPkgPath = iface.OutputPkg.PkgPath
		packageName = iface.OutputPkg.Types.Name()
	}

	// Import identifiers (type packages, provider packages, context, fmt,
	// testing) are one collision domain: every import in the file needs a
	// distinct local identifier.
	importAlloc := NewAllocator()
	imps := newImportSet(targetPkgPath, importAlloc)
	imps.add("context", "context")
	imps.add("fmt", "fmt")

	// When the output variant writes into a different directory than the
	// one the interface is declared in, the interface itself becomes just
	// another import, qualified like any cross-package reference.
	ifaceRef := iface.IfaceName
	ifaceIdent := ""
	if iface.EffectiveDir != iface.PkgDir {
		ifaceIdent = imps.add(iface.Pkg.PkgPath, iface.Pkg.Types.Name())
		ifaceRef = ifaceIdent + "." + iface.IfaceName
	}

	type methodPrep struct {
		Name             string
		TypeStr          string
		ProviderCall     string
		ProviderFuncName string
		ConstructorRef   string // import identifier this method's provider call uses inside the constructor, "" if the call is unqualified (local provider)
	}

	prepared := make([]methodPrep, 0, len(iface.Methods))
	for _, m := range iface.Methods {
		typeStr := types.TypeString(m.Type, imps.qualifier())

		providerCall := m.Provider.Func.Name()
		constructorRef := ""
		if m.Provider.Pkg.PkgPath != targetPkgPath {
			ident := imps.add(m.Provider.Pkg.PkgPath, m.Provider.Pkg.Types.Name())
			providerCall = ident + "." + providerCall
			constructorRef = ident
		}

		prepared = append(prepared, methodPrep{
			Name:             m.Name,
			TypeStr:          typeStr,
			ProviderCall:     providerCall,
			ProviderFuncName: m.Provider.Func.Name(),
			ConstructorRef:   constructorRef,
		})
	}

	testingIdent := importAlloc.Alloc("testing")
	testingEntry := importEntry{Path: "testing", Ident: testingIdent}
	if testingIdent != "testing" {
		testingEntry.Alias = testingIdent
	}

	// Local/cleanup variable names are a second, separate collision domain
	// scoped to the constructor's own body: they must avoid the fixed
	// names it always uses (ctx/err/cleanup/cleanups), each other, and any
	// import identifier actually referenced live within that same function
	// (context, fmt, and any cross-package provider alias) — but not a
	// type-only package import that never appears inside the constructor,
	// since shadowing that there is harmless (see case-01's local var "b"
	// vs. the "b" package import, used only in comments and other funcs).
	localAlloc := NewAllocator()
	localAlloc.Reserve("context")
	localAlloc.Reserve("fmt")
	if ifaceIdent != "" {
		localAlloc.Reserve(ifaceIdent)
	}
	for _, mp := range prepared {
		if mp.ConstructorRef != "" {
			localAlloc.Reserve(mp.ConstructorRef)
		}
	}

	methods := make([]methodData, 0, len(prepared))
	for _, mp := range prepared {
		base := lowerFirst(mp.Name)
		localVar := localAlloc.Alloc(base)
		cleanupVar := localAlloc.Alloc(localVar + "Cleanup")
		methods = append(methods, methodData{
			Name:             mp.Name,
			LocalVar:         localVar,
			CleanupVar:       cleanupVar,
			FieldName:        base,
			TypeStr:          mp.TypeStr,
			ProviderCall:     mp.ProviderCall,
			ProviderFuncName: mp.ProviderFuncName,
		})
	}

	structName := lowerFirst(iface.Output.Name) + iface.IfaceName
	data := fileData{
		PackageName:     packageName,
		ConstructorName: "New" + iface.Output.Name + iface.IfaceName,
		IfaceRef:        ifaceRef,
		StructName:      structName,
		TestStructName:  iface.Output.Name + "Test" + iface.IfaceName,
		TestCtorName:    "New" + iface.Output.Name + "Test" + iface.IfaceName,
		GroupA:          imps.entries(),
		GroupB:          []importEntry{testingEntry},
		Methods:         methods,
	}

	var buf bytes.Buffer
	if err := fileTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("tack: render template: %w", err)
	}

	filename := OutputFilename(iface.Output, iface.IfaceName)
	formatted, err := imports.Process(filename, buf.Bytes(), &imports.Options{
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
		FormatOnly: true,
	})
	if err != nil {
		return nil, fmt.Errorf("tack: format generated output for %s: %w", filename, err)
	}
	return formatted, nil
}
